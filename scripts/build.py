"""Build the single-file AFM Journey page.

Reads   src/index.template.html, data/journey-data.js and vendor/*
Writes  dist/index.html: one self-contained file with the data, GSAP, fonts and
        icons inlined, so it works offline, by double-click and on GitHub Pages.

    python scripts/build.py

Standard library only. The GitHub Actions workflow runs this on every push.
"""
from __future__ import annotations

import base64
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "src" / "index.template.html"
DATA = ROOT / "data" / "journey-data.js"
VENDOR = ROOT / "vendor"
OUT = ROOT / "dist" / "index.html"


def b64(path: Path) -> str:
    return "data:font/woff2;base64," + base64.b64encode(path.read_bytes()).decode("ascii")


def js(path: Path) -> str:
    # Stop "</script" inside a library or the data from closing the inline tag.
    return path.read_text(encoding="utf-8").replace("</script", "<\\/script")


def font_css() -> str:
    """Latin + Latin-ext subsets only, one @font-face per file with a weight range
    (Geist and Geist Mono are variable fonts: every weight points at the same file)."""
    css = (VENDOR / "fonts" / "fonts.css").read_text(encoding="utf-8")
    faces: dict[tuple[str, str], dict] = {}
    for block in re.findall(r"@font-face\s*\{[^}]*\}", css):
        rng = re.search(r"unicode-range:\s*([^;]+);", block).group(1)
        if not (rng.startswith("U+0000-00FF") or rng.startswith("U+0100-02BA")):
            continue
        fam = re.search(r"font-family:\s*'([^']+)'", block).group(1)
        url = re.search(r"url\(([^)]+)\)", block).group(1)
        weight = int(re.search(r"font-weight:\s*(\d+)", block).group(1))
        faces.setdefault((fam, url), {"rng": rng, "w": []})["w"].append(weight)
    return "\n".join(
        "@font-face{font-family:'%s';font-style:normal;font-weight:%d %d;font-display:swap;"
        "src:url(%s) format('woff2');unicode-range:%s}"
        % (fam, min(f["w"]), max(f["w"]), b64(VENDOR / "fonts" / url), f["rng"])
        for (fam, url), f in faces.items()
    )


def icon_css() -> str:
    css = (VENDOR / "phosphor" / "style.css").read_text(encoding="utf-8")
    return re.sub(
        r"src:\s*url\(\"\./Phosphor\.woff2\"\)[^;]*;",
        'src:url(%s) format("woff2");' % b64(VENDOR / "phosphor" / "Phosphor.woff2"),
        css,
    )


def main() -> None:
    html = SRC.read_text(encoding="utf-8")
    swaps = {
        '<link rel="stylesheet" href="../vendor/fonts/fonts.css">': "<style>\n%s\n</style>" % font_css(),
        '<link rel="stylesheet" href="../vendor/phosphor/style.css">': "<style>\n%s\n</style>" % icon_css(),
        '<script src="../data/journey-data.js"></script>': "<script>\n%s\n</script>" % js(DATA),
        '<script src="../vendor/gsap.min.js"></script>': "<script>\n%s\n</script>" % js(VENDOR / "gsap.min.js"),
        '<script src="../vendor/ScrollTrigger.min.js"></script>': "<script>\n%s\n</script>" % js(VENDOR / "ScrollTrigger.min.js"),
        '<script src="../vendor/Flip.min.js"></script>': "<script>\n%s\n</script>" % js(VENDOR / "Flip.min.js"),
    }
    for tag, inline in swaps.items():
        if tag not in html:
            raise SystemExit("Template is missing: " + tag)
        html = html.replace(tag, inline)
    banner = "<!-- GENERATED by scripts/build.py from src/index.template.html + data/journey-data.js. Do not edit. -->"
    head, sep, rest = html.partition(">")  # keep <!doctype html> as the very first thing
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(head + sep + "\n" + banner + rest, encoding="utf-8")
    print("Built %s (%.0f KB)" % (OUT.relative_to(ROOT).as_posix(), OUT.stat().st_size / 1024))


if __name__ == "__main__":
    main()
